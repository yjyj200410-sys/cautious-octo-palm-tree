// Count remaining English
function countEn(obj) {
  let c = 0;
  for (const [key, value] of Object.entries(obj)) {
    if (typeof value === 'string' && /[a-zA-Z]{3,}/.test(value) && !value.startsWith('{{count}}') && !value.startsWith('$t(')) {
      c++;
    } else if (typeof value === 'object' && value !== null && !Array.isArray(value)) {
      c += countEn(value);
    }
  }
  return c;
}

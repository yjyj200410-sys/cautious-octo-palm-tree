// Apply translations
function apply(obj, depth = 0) {
  for (const [key, value] of Object.entries(obj)) {
    if (typeof value === 'string' && map[value]) {
      obj[key] = map[value];
    } else if (typeof value === 'object' && value !== null && !Array.isArray(value)) {
      apply(value, depth + 1);
    }
  }
  return obj;
}

apply(zh);

// Also handle embedded English in mixed strings
function fixMixed(obj) {
  for (const [key, value] of Object.entries(obj)) {
    if (typeof value === 'string') {
      // Fix common patterns where English remains in translated strings
      let s = value;
      for (const [en, zh] of Object.entries(map)) {
        if (en.length >= 3 && s.includes(en)) {
          s = s.replace(new RegExp(en.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g'), zh);
        }
      }
      obj[key] = s;
    } else if (typeof value === 'object' && value !== null && !Array.isArray(value)) {
      fixMixed(value);
    }
  }
  return obj;
}
fixMixed(zh);

